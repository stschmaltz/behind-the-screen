import { NextPage } from 'next';
import { useCallback, useEffect, useState } from 'react';
import { useUser } from '@auth0/nextjs-auth0/client';
import Link from 'next/link';
import posthog from 'posthog-js';
import { ChevronDownIcon, ChevronUpIcon } from '@heroicons/react/24/outline';
import {
  LootDisplay,
  LootGeneratorForm,
  LootItemType,
} from '../components/loot';
import type {
  AiModeConfig,
  LootFormValues,
} from '../components/loot/LootGeneratorForm';
import {
  GenerationEntry,
  useLootHistory,
} from '../hooks/use-loot-history.hook';
import LootHistory from '../components/loot/LootHistory';
import { asyncFetch } from '../data/graphql/graphql-fetcher';
import { useGenerationUsage } from '../hooks/use-generation-usage';
import { useCurrentUserContext } from '../context/UserContext';
import { SignInForAi } from '../components/generators/SignInForAi';
import { ToolSeoContent } from '../components/seo/ToolSeoContent';
import { JsonLd } from '../components/seo/JsonLd';
import { buildWebAppJsonLd, FaqItem } from '../lib/seo';
import { generateFreeLoot } from '../lib/generate-free-loot';

// ============================================================================
// GraphQL
// ============================================================================

const GENERATE_LOOT_MUTATION = `
  mutation GenerateLoot($partyLevel: Int!, $srdItemCount: Int!, $randomItemCount: Int!, $context: String, $lootQuality: String, $includeEffects: Boolean) {
    generateLoot(
      partyLevel: $partyLevel
      srdItemCount: $srdItemCount
      randomItemCount: $randomItemCount
      context: $context
      lootQuality: $lootQuality
      includeEffects: $includeEffects
    ) {
      level
      coins
      item
      description
      note
      source
      rarity
      effects
    }
  }
`;

// ============================================================================
// Default Values
// ============================================================================

const DEFAULT_FORM_VALUES: LootFormValues = {
  partyLevel: 3,
  srdItemCount: 4,
  randomItemCount: 3,
  context: '',
  lootQuality: 'standard',
  includeEffects: true,
};

const STEPS = [
  {
    title: 'Set the party level',
    body: 'Enter a level from 1 to 20 and how many items you want so the haul fits your party.',
  },
  {
    title: 'Generate',
    body: 'Get coins plus adventuring gear, weapons, armor and trinkets. Sign in to add official magic items and AI-made custom loot.',
  },
  {
    title: 'Hand it out',
    body: 'Each roll is saved to your history on this device so you can reuse or revisit a hoard later.',
  },
];

const FAQS: FaqItem[] = [
  {
    question: 'Is the loot generator free?',
    answer:
      'Yes. Random coins, gear and trinkets are free and work without an account. Signing in (also free) unlocks official magic items and AI-generated custom loot themed to a location, with a weekly usage allowance.',
  },
  {
    question: 'Where do the magic items come from?',
    answer:
      'When you are signed in, official items come from the D&D 5e System Reference Document (SRD 5.1), used under the Open Game License, and custom items are generated by AI.',
  },
  {
    question: 'Does the loot scale with party level?',
    answer:
      'Yes. Coin amounts grow with the party level you enter, from level 1 through 20, and signed-in rolls pick items to suit that level.',
  },
  {
    question: 'Are my loot rolls saved?',
    answer:
      'Your recent rolls are kept in the history panel in your browser on this device, so you can reopen or delete them at any time.',
  },
];

const RELATED_TOOLS = [
  {
    href: '/npc-generator',
    label: 'NPC Generator',
    description: 'Create memorable NPCs with personality and quirks.',
  },
  {
    href: '/encounters',
    label: 'Encounter Manager',
    description: 'Track initiative, HP and conditions during combat.',
  },
];

// ============================================================================
// Page Component
// ============================================================================

const LootGeneratorPage: NextPage = () => {
  const { user, isLoading: isLoadingAuth } = useUser();
  const { currentUser } = useCurrentUserContext();
  const isSignedIn = Boolean(currentUser);
  const isCheckingSession = isLoadingAuth || (Boolean(user) && !isSignedIn);

  // Form state
  const [formValues, setFormValues] =
    useState<LootFormValues>(DEFAULT_FORM_VALUES);
  const [useAiEnhanced, setUseAiEnhanced] = useState(true);

  // UI state
  const [loot, setLoot] = useState<LootItemType[] | null>(null);
  const [isGenerating, setIsGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [isFormCollapsed, setIsFormCollapsed] = useState(false);

  // Hooks
  const { history, addEntry, removeEntry, clearHistory } = useLootHistory();
  const {
    remainingUses,
    hasAvailableUses,
    hasRequestedMoreUses,
    requestMoreUses,
    refetch: refetchUsage,
    isLoading: isLoadingUsage,
  } = useGenerationUsage({ enabled: isSignedIn });
  const aiEnabled = useAiEnhanced && isSignedIn && hasAvailableUses;

  // Disable AI mode if no uses available
  useEffect(() => {
    if (isSignedIn && !isLoadingUsage && !hasAvailableUses) {
      setUseAiEnhanced(false);
    }
  }, [hasAvailableUses, isSignedIn, isLoadingUsage]);

  // Derived state
  const aiMode: AiModeConfig = {
    enabled: aiEnabled,
    remainingUses,
    hasAvailableUses,
    hasRequestedMoreUses,
  };

  // Handlers
  const handleFormChange = useCallback((updates: Partial<LootFormValues>) => {
    setFormValues((prev) => ({ ...prev, ...updates }));
  }, []);

  const handleHistorySelect = useCallback((entry: GenerationEntry) => {
    setFormValues({
      partyLevel: entry.partyLevel,
      srdItemCount: entry.srdItemCount,
      randomItemCount: entry.randomItemCount,
      context: entry.context,
      lootQuality: 'standard', // History doesn't store this, use default
      includeEffects: true, // History doesn't store this, use default
    });
    setLoot(entry.loot);
    setError(null);
    setIsFormCollapsed(false);
  }, []);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsGenerating(true);
    setError(null);
    setLoot(null);

    const {
      partyLevel,
      srdItemCount,
      randomItemCount,
      context,
      lootQuality,
      includeEffects,
    } = formValues;

    const isUsingAiFeatures =
      aiEnabled && (randomItemCount > 0 || context.trim().length > 0);

    try {
      let generatedLoot: LootItemType[];

      if (aiEnabled) {
        const data = await asyncFetch<{ generateLoot: LootItemType[] }>(
          GENERATE_LOOT_MUTATION,
          {
            partyLevel,
            srdItemCount,
            randomItemCount,
            context,
            lootQuality,
            includeEffects,
          },
        );
        generatedLoot = data.generateLoot;

        if (isUsingAiFeatures) {
          refetchUsage();
        }
      } else {
        generatedLoot = generateFreeLoot(partyLevel, srdItemCount);
      }

      setLoot(generatedLoot);

      // Analytics
      posthog.capture('loot_generated', {
        use_ai_enhanced: aiEnabled,
        party_level: partyLevel,
        srd_item_count: srdItemCount,
        random_item_count: randomItemCount,
        has_context: !!context,
        loot_quality: lootQuality,
        is_using_ai_features: isUsingAiFeatures,
        total_items: generatedLoot.length,
      });

      addEntry({
        partyLevel,
        srdItemCount,
        randomItemCount: aiEnabled ? randomItemCount : 0,
        context: aiEnabled ? context : '',
        loot: generatedLoot,
      });
      setIsFormCollapsed(true);
    } catch (err: unknown) {
      const message =
        err instanceof Error ? err.message : 'An unknown error occurred.';
      setError(message || 'Failed to generate loot.');
      if (err instanceof Error) posthog.captureException(err);
    }
    setIsGenerating(false);
  };

  // Collapsed form summary
  const formSummary = `Level ${formValues.partyLevel} • ${formValues.srdItemCount} Official + ${formValues.randomItemCount} AI Items${formValues.context ? ` • ${formValues.context}` : ''}`;

  return (
    <div className="pb-8">
      <JsonLd
        id="loot-generator-app"
        data={buildWebAppJsonLd({
          name: 'D&D 5e Loot Generator',
          description: 'Free random loot and treasure generator for D&D 5e.',
          path: '/loot-generator',
        })}
      />
      <div className="max-w-6xl mx-auto space-y-6">
        <header className="text-center space-y-2">
          <h1 className="text-3xl md:text-4xl font-bold text-balance">
            Free D&amp;D 5e Loot Generator
          </h1>
          <p className="max-w-2xl mx-auto text-base-content/70 text-balance">
            Roll treasure for your party in seconds: coins, gear and trinkets
            scaled to party level, ready to hand out at the end of an encounter.
          </p>
          <p className="text-xs text-base-content/60">
            <span className="badge badge-accent badge-sm mr-2">Beta</span>
            Have feedback or ideas?{' '}
            <Link href="/feedback" className="link link-primary">
              Let me know!
            </Link>
          </p>
        </header>

        {/* Form Section */}
        <div className="relative">
          {loot && !isGenerating && (
            <button
              onClick={() => setIsFormCollapsed(!isFormCollapsed)}
              className="absolute top-4 right-4 z-10 btn btn-sm btn-circle btn-ghost"
              title={isFormCollapsed ? 'Expand form' : 'Collapse form'}
            >
              {isFormCollapsed ? (
                <ChevronDownIcon className="w-5 h-5" />
              ) : (
                <ChevronUpIcon className="w-5 h-5" />
              )}
            </button>
          )}

          <div
            className={`transition-all duration-300 ${
              isFormCollapsed
                ? 'max-h-0 overflow-hidden opacity-0'
                : 'max-h-[2000px] opacity-100'
            }`}
          >
            <LootGeneratorForm
              values={formValues}
              onChange={handleFormChange}
              aiMode={aiMode}
              onAiModeChange={setUseAiEnhanced}
              onRequestMoreUses={requestMoreUses}
              isLoading={isGenerating}
              error={error}
              onSubmit={handleSubmit}
              aiSlot={
                isSignedIn ? undefined : (
                  <SignInForAi
                    returnTo="/loot-generator"
                    isCheckingSession={isCheckingSession}
                  />
                )
              }
            />
          </div>

          {isFormCollapsed && loot && (
            <div className="card bg-base-100 shadow-lg">
              <div className="card-body py-3 px-6">
                <p className="text-sm text-base-content/70">{formSummary}</p>
              </div>
            </div>
          )}
        </div>

        {/* Loot Display */}
        {(loot || isGenerating) && (
          <div className="w-full">
            <LootDisplay
              loot={loot}
              context={formValues.context}
              isGenerating={isGenerating}
            />
          </div>
        )}

        {/* History */}
        <div className="w-full">
          <LootHistory
            history={history}
            onSelect={handleHistorySelect}
            onDelete={removeEntry}
            onClear={clearHistory}
          />
        </div>

        <ToolSeoContent
          id="loot-generator"
          howItWorksTitle="How the loot generator works"
          steps={STEPS}
          faqs={FAQS}
          relatedTools={RELATED_TOOLS}
        />
      </div>
    </div>
  );
};

export default LootGeneratorPage;
